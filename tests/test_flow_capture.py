import struct
import tempfile
import unittest
from unittest import mock
import zlib

from tools import audit_flow_capture as flow


def reverse_bits(value, width):
    return int(f"{value:0{width}b}"[::-1], 2)


def mpeg2_crc_bytes(data):
    """Independent oracle: transform reflected zlib CRC into non-reflected CRC."""
    reflected_input = bytes(reverse_bits(byte, 8) for byte in data)
    return reverse_bits(zlib.crc32(reflected_input) ^ 0xFFFFFFFF, 32)


def reference_crc(data):
    # STM32's little-endian word load sends each word's MSB through the CRC first.
    assert len(data) % 4 == 0
    return mpeg2_crc_bytes(b"".join(data[i:i + 4][::-1] for i in range(0, len(data), 4)))


def seal(packet):
    struct.pack_into("<I", packet, flow.CRC_OFFSET, reference_crc(packet[:flow.CRC_OFFSET]))
    return bytes(packet)


def packet(power=50, alc=80, flags=2, fmt=0):
    frame = bytearray(flow.FRAME_BYTES)
    frame[:4] = flow.MAGIC
    struct.pack_into("<I", frame, 0x1004, flags)
    frame[0x1008:0x1010] = bytes((231, power, 13, alc, 135, 81, 72, 219))
    struct.pack_into("<I", frame, 0x1010, 0x12345678)
    frame[0x1018] = fmt
    struct.pack_into("<I", frame, 0x1020, 0xC1)
    return seal(frame)


class SavedFlowAudit(unittest.TestCase):
    def audit(self, data, profile="oem", limit=16, chunk_bytes=65536):
        return flow._audit_stream(io.BytesIO(data), profile, limit, chunk_bytes)

    def test_independent_crc_vectors(self):
        self.assertEqual(mpeg2_crc_bytes(b"123456789"), 0x0376E6E7)
        # Golden values generated by the original X6100Control crc32.c at
        # 7a5bb8e5367f59003ef03af221361e186da10bf0, not by this Python code.
        vectors = ((b"", 0xFFFFFFFF), (bytes(4), 0xC704DD7B),
                   (bytes.fromhex("78563412"), 0xDF8A8A2B),
                   (bytes.fromhex("0102030405060708"), 0xA3141BDA))
        for data, expected in vectors:
            with self.subTest(data=data):
                self.assertEqual(flow.stm32_crc32(data), expected)
                self.assertEqual(reference_crc(data), expected)
        with self.assertRaises(ValueError):
            flow.stm32_crc32(b"123")

    def test_independent_full_packet_crc(self):
        frame = bytearray((i * 37 + 11) & 255 for i in range(flow.FRAME_BYTES))
        frame[:4] = flow.MAGIC
        self.assertEqual(flow.stm32_crc32(frame[:flow.CRC_OFFSET]), 0xE52B5353)
        self.assertEqual(reference_crc(frame[:flow.CRC_OFFSET]), 0xE52B5353)
        frame = seal(frame)
        self.assertEqual(hashlib.sha256(frame).hexdigest(),
                         "d31f3b4fcf2100aa856f916a0f0ddf51ba74e5f57ebc69b2f08fd6aa202acb4f")
        self.assertEqual(self.audit(frame)["crc_valid_frames"], 1)

    def test_common_offsets_and_telemetry(self):
        result = self.audit(packet(flags=31))
        self.assertTrue(result["clean"])
        self.assertEqual(result["input_bytes"], 4136)
        self.assertEqual(result["crc_valid_frames"], 1)
        self.assertEqual(result["first_valid_offset"], 0)
        self.assertEqual(result["last_valid_offset"], 0)
        decoded = result["frames"][0]
        self.assertTrue(all(decoded["flags"].values()))
        self.assertEqual(decoded["telemetry"], {
            "indicated_tx_power_w": 5.0, "indicated_vswr": 1.3,
            "alc_raw": 80, "gui_alc_value": 2.0,
            "external_voltage_v": 13.5, "battery_voltage_v": 8.1,
            "battery_percent_raw": 72})
        self.assertEqual(decoded["atu_params_raw"], 0x12345678)
        self.assertEqual(decoded["hkey_raw"], 0xC1)
        self.assertEqual(decoded["iq"], {"encoding": "fp32", "complex_samples": 512,
                                         "nonfinite_components": 0})
        self.assertEqual(self.audit(packet(alc=255))["frames"][0]["telemetry"]["gui_alc_value"], 0)

    def test_noise_corruption_resync_and_crc_gates_telemetry(self):
        bad = bytearray(packet(power=255, alc=0))
        bad[12] ^= 1
        leading = b"noise"
        middle = b"trash"
        good = packet(power=37)
        data = leading + bytes(bad) + middle + good
        result = self.audit(data, chunk_bytes=113)
        self.assertFalse(result["clean"])
        self.assertEqual(result["crc_failed_candidates"], 1)
        self.assertEqual(result["decoded_frames"], 1)
        self.assertEqual(result["first_valid_offset"], len(leading) + len(bad) + len(middle))
        self.assertEqual(result["unframed_bytes"], len(data) - len(good))
        self.assertEqual(result["trailing_unframed_bytes"], 0)
        self.assertEqual(result["resync_events"], 1)
        self.assertEqual(result["telemetry_ranges"]["indicated_tx_power_w"], {"min": 3.7, "max": 3.7})
        self.assertEqual(result["telemetry_ranges"]["alc_raw"], {"min": 80, "max": 80})
        self.assertEqual(result["sha256"], hashlib.sha256(data).hexdigest())

    def test_valid_frame_ignores_false_magic_inside_payload(self):
        frame = bytearray(packet())
        frame[64:68] = flow.MAGIC
        result = self.audit(seal(frame) + packet(), chunk_bytes=17)
        self.assertTrue(result["clean"])
        self.assertEqual(result["crc_valid_frames"], 2)
        self.assertEqual(result["crc_failed_candidates"], 0)
        self.assertEqual([x["offset"] for x in result["frames"]], [0, flow.FRAME_BYTES])

    def test_false_magic_in_corrupt_candidate_recovers(self):
        frame = bytearray(packet(power=250))
        frame[64:68] = flow.MAGIC  # Deliberately not re-sealed.
        result = self.audit(bytes(frame) + packet(power=40))
        self.assertEqual(result["crc_failed_candidates"], 2)
        self.assertEqual(result["decoded_frames"], 1)
        self.assertEqual(result["last_valid_offset"], flow.FRAME_BYTES)
        self.assertEqual(result["telemetry_ranges"]["indicated_tx_power_w"]["max"], 4)

    def test_truncated_frame_can_resync_to_later_complete_frame(self):
        partial = packet(power=250)[:200]
        result = self.audit(partial + packet(power=40), chunk_bytes=127)
        self.assertEqual(result["crc_failed_candidates"], 1)
        self.assertEqual(result["decoded_frames"], 1)
        self.assertEqual(result["first_valid_offset"], 200)
        self.assertEqual(result["unframed_bytes"], 200)
        self.assertIsNone(result["incomplete_tail"])

    def test_incomplete_tail_and_split_magic(self):
        result = self.audit(packet() + b"x" + packet()[:201], chunk_bytes=1)
        self.assertEqual(result["decoded_frames"], 1)
        self.assertEqual(result["incomplete_tail"], {
            "kind": "frame_candidate", "offset": flow.FRAME_BYTES + 1, "bytes": 201})
        self.assertEqual(result["unframed_bytes"], 202)
        for size in (1, 2, 3):
            result = self.audit(packet() + flow.MAGIC[:size], chunk_bytes=31)
            self.assertEqual(result["incomplete_tail"], {
                "kind": "magic_prefix", "offset": flow.FRAME_BYTES, "bytes": size})
            self.assertFalse(result["clean"])

    def test_empty_and_noise_only_files(self):
        for data in (b"", b"noise", b"a" * 9000):
            result = self.audit(data)
            self.assertFalse(result["clean"])
            self.assertEqual(result["crc_valid_frames"], 0)
            self.assertEqual(result["unframed_bytes"], len(data))
            self.assertEqual(result["telemetry_ranges"], {})
            self.assertIsNone(result["incomplete_tail"])

    def test_oem_ignores_reserved_flow_info(self):
        frame = bytearray(packet())
        frame[0x1014:0x1020] = bytes.fromhex("78563412ff93ffff99887766")
        result = self.audit(seal(frame), "oem")
        self.assertTrue(result["clean"])
        self.assertEqual(result["iq_format_counts"], {"fp32": 1})
        self.assertNotIn("flow_info", result["frames"][0])
        # A reserved byte of 1 still must not silently switch alpha.2 to BF16.
        frame[0x1018] = 1
        self.assertEqual(self.audit(seal(frame))["iq_complex_samples"], 512)

    def test_extended_bf16_and_verified_metadata_layout(self):
        frame = bytearray(packet(fmt=1))
        # Serialized layout independently produced by X6100Control's C header.
        frame[0x1014:0x1020] = bytes.fromhex("7856341201934b0600000000")
        struct.pack_into("<HHHH", frame, 4, 0x3F80, 0xBF80, 0x7F7F, 0x0001)
        result = self.audit(seal(frame), "extended-r8")
        self.assertTrue(result["clean"])
        self.assertEqual(result["iq_format_counts"], {"bf16": 1})
        self.assertEqual(result["iq_complex_samples"], 1024)
        self.assertEqual(result["frames"][0]["flow_info"], {
            "lo_frequency_raw": 0x12345678, "format_raw": 1, "sequence_index_raw": 3,
            "sequence_total_raw": 9, "vary_frequency": True, "fft_decimation_raw": 5,
            "audio_input_level_raw": 100})

    def test_unknown_extended_format_never_falls_back(self):
        result = self.audit(packet(power=255, fmt=7) + packet(power=25), "extended-r8")
        self.assertFalse(result["clean"])
        self.assertEqual(result["crc_valid_frames"], 2)
        self.assertEqual(result["decoded_frames"], 1)
        self.assertEqual(result["unsupported_format_frames"], 1)
        self.assertEqual(result["iq_format_counts"], {"fp32": 1})
        self.assertEqual(result["telemetry_ranges"]["indicated_tx_power_w"]["max"], 2.5)
        self.assertEqual(result["events"][0], {"kind": "unsupported_format", "offset": 0, "format_raw": 7})

    def test_nonfinite_iq_components_in_both_formats(self):
        for fmt, payload in ((0, struct.pack("<IIII", 0x7F800000, 0xFF800000, 0x7FC00001, 0x7F7FFFFF)),
                             (1, struct.pack("<HHHH", 0x7F80, 0xFF80, 0x7FC1, 0x7F7F))):
            frame = bytearray(packet(fmt=fmt))
            frame[4:4 + len(payload)] = payload
            result = self.audit(seal(frame), "extended-r8")
            self.assertFalse(result["clean"])
            self.assertEqual(result["nonfinite_iq_frames"], 1)
            self.assertEqual(result["iq_nonfinite_components"], 3)
            json.dumps(result, allow_nan=False)

    def test_does_not_repair_changed_hkey_crc(self):
        frame = bytearray(packet(power=255))
        struct.pack_into("<I", frame, 0x1020, 0xC2)
        result = self.audit(packet(power=20) + bytes(frame))
        self.assertEqual(result["crc_failed_candidates"], 1)
        self.assertEqual(result["decoded_frames"], 1)
        self.assertEqual(result["telemetry_ranges"]["indicated_tx_power_w"]["max"], 2)

    def test_detail_arrays_are_bounded_without_losing_counts(self):
        result = self.audit((b"!" + packet()) * 20, limit=2)
        self.assertEqual(result["decoded_frames"], 20)
        self.assertEqual(len(result["frames"]), 2)
        self.assertEqual(result["omitted_frame_details"], 18)
        self.assertEqual(len(result["events"]), 2)
        self.assertEqual(result["event_count"], 20)
        self.assertEqual(result["omitted_event_details"], 18)
        self.assertEqual(result["resync_events"], 20)
        self.assertEqual(result["unframed_bytes"], 20)
        zero = self.audit(packet(), limit=0)
        self.assertEqual(zero["frames"], [])
        self.assertEqual(zero["decoded_frames"], 1)

    def test_regular_file_and_explicit_profile(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "capture.bin"
            path.write_bytes(packet())
            self.assertTrue(flow.audit_file(path, "oem")["clean"])
            for profile in (None, "auto", "alpha2"):
                with self.assertRaises(ValueError):
                    flow.audit_file(path, profile)
            for limit in (-1, 1001):
                with self.assertRaises(ValueError):
                    flow.audit_file(path, "oem", limit)

    def test_rejects_devices_fifo_directory_and_symlinks_before_open(self):
        with tempfile.TemporaryDirectory() as directory:
            folder = Path(directory)
            fifo = folder / "fifo"
            os.mkfifo(fifo)
            regular = folder / "capture.bin"
            regular.write_bytes(packet())
            symlink = folder / "link"
            symlink.symlink_to(regular)
            for path in (Path("/dev/null"), fifo, folder, symlink):
                with self.subTest(path=path), mock.patch.object(flow.os, "open") as opener:
                    with self.assertRaisesRegex(ValueError, "regular file"):
                        flow.audit_file(path, "oem")
                    opener.assert_not_called()

    def test_post_open_identity_recheck_and_fd_cleanup(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "capture.bin"
            path.write_bytes(packet())
            changed = mock.Mock(st_mode=stat_mode_regular(), st_dev=-1, st_ino=-1)
            original_close = os.close
            with mock.patch.object(flow.os, "fstat", return_value=changed), \
                    mock.patch.object(flow.os, "close", wraps=original_close) as close:
                with self.assertRaisesRegex(ValueError, "changed while opening"):
                    flow.audit_file(path, "oem")
                close.assert_called_once()

    def test_cli_json_and_exit_codes(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "capture.bin"
            path.write_bytes(packet())
            stdout = io.StringIO()
            with contextlib.redirect_stdout(stdout):
                self.assertEqual(flow.main([str(path), "--profile", "oem", "--detail-limit", "0"]), 0)
            self.assertTrue(json.loads(stdout.getvalue())["clean"])
            path.write_bytes(packet()[:-1])
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(flow.main([str(path), "--profile", "oem"]), 1)
            with contextlib.redirect_stderr(io.StringIO()), self.assertRaises(SystemExit) as caught:
                flow.main([str(path)])
            self.assertEqual(caught.exception.code, 2)


def stat_mode_regular():
    import stat
    return stat.S_IFREG | 0o600


if __name__ == "__main__":
    unittest.main()
